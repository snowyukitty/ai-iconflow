"""The ``android`` target: adaptive layers, themed icon, legacy launchers.

Golden tests: the file set and the XML are compared byte for byte, and the
geometry that matters (where the safe zone lands, what the legacy shapes
keep) is measured on the PNGs. Rendering is faked; the bytes under test are
the composition IconFlow itself does.
"""
import importlib
import io
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

from PIL import Image, ImageDraw

build = importlib.import_module("iconflow.build")

DENSITIES = {"mdpi": 1.0, "hdpi": 1.5, "xhdpi": 2.0, "xxhdpi": 3.0, "xxxhdpi": 4.0}

GOLDEN_FILES = sorted(
    [f"android/res/mipmap-{d}/{name}.png" for d in DENSITIES
     for name in ("ic_launcher", "ic_launcher_round", "ic_launcher_foreground",
                  "ic_launcher_monochrome")]
    + [
        "android/res/mipmap-anydpi-v26/ic_launcher.xml",
        "android/res/mipmap-anydpi-v26/ic_launcher_round.xml",
        "android/res/values/ic_launcher_background.xml",
        "android/play-store-512.png",
    ]
)

GOLDEN_ADAPTIVE_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- AUTO-GENERATED by IconFlow. Rebuild from the SVG source; do not edit. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome"/>
</adaptive-icon>
"""

GOLDEN_BACKGROUND_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- AUTO-GENERATED by IconFlow. Rebuild from the SVG source; do not edit. -->
<resources>
    <color name="ic_launcher_background">#11142A</color>
</resources>
"""


def mark_png(size, color=(198, 242, 78, 255), *, full=False):
    """A sparse disc (a usable mark), or a full opaque square (a full card)."""
    image = Image.new("RGBA", (size, size), color if full else (0, 0, 0, 0))
    if not full:
        inset = max(1, size // 5)
        ImageDraw.Draw(image).ellipse([inset, inset, size - inset - 1, size - inset - 1], fill=color)
    out = io.BytesIO()
    image.save(out, "PNG")
    return out.getvalue()


class Cache:
    def __init__(self, *, full=False, color=(198, 242, 78, 255)):
        self.full = full
        self.color = color
        self.sizes = []

    def png(self, size):
        self.sizes.append(size)
        return mark_png(size, self.color, full=self.full)


def image(data):
    return Image.open(io.BytesIO(data)).convert("RGBA")


class AndroidTargetTests(unittest.TestCase):
    def assets(self, **kwargs):
        return build.preview_assets(Cache(), "android", bg_color="#11142a", **kwargs)

    def test_golden_file_set(self):
        self.assertEqual(sorted(self.assets()), GOLDEN_FILES)

    def test_golden_xml(self):
        assets = self.assets()
        for name in ("ic_launcher.xml", "ic_launcher_round.xml"):
            self.assertEqual(
                assets[f"android/res/mipmap-anydpi-v26/{name}"].decode("utf-8"),
                GOLDEN_ADAPTIVE_XML,
            )
        self.assertEqual(
            assets["android/res/values/ic_launcher_background.xml"].decode("utf-8"),
            GOLDEN_BACKGROUND_XML,
        )

    def test_every_density_has_the_platform_pixel_size(self):
        assets = self.assets()
        for density, factor in DENSITIES.items():
            layer = round(108 * factor)
            legacy = round(48 * factor)
            for name, size in (
                ("ic_launcher_foreground", layer), ("ic_launcher_monochrome", layer),
                ("ic_launcher", legacy), ("ic_launcher_round", legacy),
            ):
                png = image(assets[f"android/res/mipmap-{density}/{name}.png"])
                self.assertEqual(png.size, (size, size), f"{density}/{name}")
        self.assertEqual(image(assets["android/play-store-512.png"]).size, (512, 512))

    def test_artwork_is_rendered_natively_at_the_size_it_occupies(self):
        cache = Cache()
        build.android_assets(cache, "#11142a")
        # The canvas maps onto the 66dp safe circle's 82.5dp box at scale 0.8.
        expected = {round(round(108 * f) * 0.8 * 82.5 / 108) for f in DENSITIES.values()}
        self.assertTrue(expected <= set(cache.sizes), (expected, cache.sizes))

    def test_the_maskable_safe_circle_lands_on_androids_66dp_circle(self):
        # The default master composition puts the artwork's canvas in 0.611 of
        # the layer: exactly 66/108, Android's guaranteed safe diameter.
        self.assertAlmostEqual(build.android_layer_scale(None, linked=False), 66 / 108, places=6)
        assets = build.android_assets(Cache(full=True), "#11142a", monochrome_cache=Cache())
        layer = image(assets["android/res/mipmap-xxxhdpi/ic_launcher_foreground.png"])
        box = layer.getchannel("A").getbbox()
        side = box[2] - box[0]
        self.assertAlmostEqual(side / 432, 0.8 * 82.5 / 108, delta=0.01)
        self.assertEqual(layer.getpixel((0, 0))[3], 0)  # transparent outside the art

    def test_maskable_scale_resizes_every_adaptive_layer(self):
        small = build.android_assets(Cache(full=True), "#11142a", maskable_scale=0.6,
                                     monochrome_cache=Cache())
        layer = image(small["android/res/mipmap-xxxhdpi/ic_launcher_foreground.png"])
        box = layer.getchannel("A").getbbox()
        self.assertAlmostEqual((box[2] - box[0]) / 432, 0.6 * 82.5 / 108, delta=0.01)

    def test_monochrome_is_the_marks_alpha(self):
        assets = self.assets()
        mono = image(assets["android/res/mipmap-xxxhdpi/ic_launcher_monochrome.png"])
        self.assertEqual(mono.getpixel((216, 216)), (0, 0, 0, 255))
        self.assertEqual(mono.getpixel((5, 5))[3], 0)

    def test_monochrome_prefers_a_linked_mark_only_source(self):
        class Ring(Cache):
            def png(self, size):
                im = Image.new("RGBA", (size, size), (0, 0, 0, 0))
                ImageDraw.Draw(im).ellipse([0, 0, size - 1, size - 1], outline=(0, 0, 0, 255),
                                           width=max(1, size // 8))
                out = io.BytesIO()
                im.save(out, "PNG")
                return out.getvalue()

        assets = build.android_assets(Cache(full=True), "#11142a", monochrome_cache=Ring())
        mono = image(assets["android/res/mipmap-xxxhdpi/ic_launcher_monochrome.png"])
        self.assertEqual(mono.getpixel((216, 216))[3], 0)  # the ring's hole, not the card

    def test_a_full_card_without_a_mark_only_source_fails_closed(self):
        with self.assertRaisesRegex(ValueError, "monochrome_svg"):
            build.android_assets(Cache(full=True), "#11142a")

    def test_legacy_icons_keep_the_keyline_and_the_store_icon_is_opaque(self):
        assets = self.assets()
        square = image(assets["android/res/mipmap-xxxhdpi/ic_launcher.png"])
        round_ = image(assets["android/res/mipmap-xxxhdpi/ic_launcher_round.png"])
        self.assertEqual(square.getpixel((0, 0))[3], 0)       # 2dp keyline margin
        self.assertEqual(square.getpixel((96, 96))[3], 255)    # the mark
        self.assertEqual(square.getpixel((12, 96))[:3], (17, 20, 42))  # background edge
        self.assertEqual(round_.getpixel((14, 14))[3], 0)      # the circle's corner
        store = image(assets["android/play-store-512.png"])
        self.assertEqual(store.getpixel((0, 0)), (17, 20, 42, 255))

    def test_build_writes_the_android_tree_and_all_does_not_include_it(self):
        from iconflow import config

        self.assertNotIn("android", build.normalize_targets(["all"]))
        self.assertEqual(config.TARGETS, build.TARGETS)
        self.assertEqual(config.APP_TARGETS, build.APP_TARGETS)

        class Rasterizer:
            def __init__(self, color_scheme="light"):
                pass

            def __enter__(self):
                return self

            def __exit__(self, *exc):
                return None

            def render(self, _svg, size, bg="transparent"):
                return mark_png(size)

        with tempfile.TemporaryDirectory() as tmp:
            master = Path(tmp) / "master.svg"
            master.write_text('<svg viewBox="0 0 10 10"></svg>', encoding="utf-8")
            with patch.object(build, "Rasterizer", Rasterizer):
                produced = build.build(master, Path(tmp) / "out", ["android"], bg_color="#11142a")
            self.assertEqual(sorted(produced), GOLDEN_FILES)
            for name in GOLDEN_FILES:
                self.assertTrue((Path(tmp) / "out" / name).is_file(), name)


if __name__ == "__main__":
    unittest.main()
